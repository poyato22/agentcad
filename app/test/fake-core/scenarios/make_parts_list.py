"""Builds scenarios/parts-list.json (Plan 7 U4a e2e) from base.json plus the real-core browser/BOM
dump (core/tests/fixtures/ui/browser, written by core/scripts/dump_browser_bom_fixtures.py):
the dumped run's snapshots and part cards move to base's run, the dumped build's parts list to
the Default build, and base's run gains a part_show call whose result is the dumped one.

    python3 app/test/fake-core/scenarios/make_parts_list.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
FX = HERE.parents[3] / "core" / "tests" / "fixtures" / "ui" / "browser"
# the same Default build the fake core uses (fake-core/assembly.ts DEFAULT_PROJECT_ROW)
DEFAULT_PROJECT = json.loads((FX.parent / "projects.json").read_text())[0]["id"]


def load(name):
    return json.loads((FX / name).read_text())


base = json.loads((HERE / "base.json").read_text())
run = base["runs"][0]["id"]
base["_comment"] = ("Plan 7 U4a e2e: base plus the real-core browser/BOM dump (snapshots and part cards on the base run, "
                    "the parts list on the Default build, a part_show call in the thread). Generated by make_parts_list.py.")
snaps = load("browser_list_full.json")
for s in snaps:
    s["run_id"], s["project_id"] = run, DEFAULT_PROJECT
cards = load("browser_cards.json")
for c in cards:
    c["run_id"], c["project_id"] = run, DEFAULT_PROJECT
items = load("bom.json")["items"]
for it in items:
    it["project_id"] = DEFAULT_PROJECT
base["browser"] = {"snapshots": snaps, "cards": cards, "bom": items}

result = load("part_show_result.json")
last = base["steps"][-1]
nid, ts = last["id"], last["ts"]
snap_id = result["snapshot_id"]
base["steps"] += [
    {"id": nid + 1, "run_id": run, "ts": ts + 1, "kind": "tool_call", "payload": {
        "call_id": "c_show", "name": "part_show", "input": {"snapshot_id": snap_id}},
     "evidence_hash": "0" * 64, "prev_hash": last["evidence_hash"], "collapsed": False},
    {"id": nid + 2, "run_id": run, "ts": ts + 2, "kind": "tool_result", "payload": {
        "call_id": "c_show", "name": "part_show", "output": {
            "ok": True, "summary": f"Showed the user part card {result['card_id']}", "data": result,
            "handles": [], "warnings": [], "step_kind": "tool_result"}},
     "evidence_hash": "1" * 64, "prev_hash": "0" * 64, "collapsed": False},
]
(HERE / "parts-list.json").write_text(json.dumps(base, indent=2, ensure_ascii=False) + "\n")
print(f"wrote parts-list.json: {len(snaps)} snapshots, {len(cards)} cards, {len(items)} rows")
