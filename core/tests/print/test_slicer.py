import os
import stat
import sys
from pathlib import Path

import pytest

from mises.print import slicer
from mises.types import MisesError

FIXTURE = Path(__file__).parent / "fixtures" / "sample.gcode"


def test_parse_estimate_from_fixture():
    est = slicer.parse_estimate(FIXTURE.read_text(), usd_per_kg=22.0)
    assert est.time_s == 86400 + 2 * 3600 + 3 * 60 + 22
    assert est.time_text == "1d 2h 3m 22s"
    assert est.filament_mm == pytest.approx(2519.58)
    assert est.filament_g == pytest.approx(7.51)
    assert est.cost_usd == pytest.approx(7.51 / 1000 * 22.0, abs=1e-4)


def test_parse_estimate_missing_fields_is_error():
    with pytest.raises(MisesError, match="estimate"):
        slicer.parse_estimate("G28\n", usd_per_kg=22.0)


def test_extract_thumbnail_png():
    png = slicer.extract_thumbnail(FIXTURE.read_text())
    assert png is not None and png.startswith(b"\x89PNG")
    assert slicer.extract_thumbnail("G28\n") is None


def test_thumbnail_tolerates_trailing_whitespace():
    lines = FIXTURE.read_text().split("\n")
    lines = [ln + " \t" if ln.startswith("; thumbnail begin") or ln.startswith("; iVBOR")
             else ln for ln in lines]
    assert slicer.extract_thumbnail("\n".join(lines)).startswith(b"\x89PNG")


def test_find_slicer_missing(monkeypatch, tmp_path):
    monkeypatch.delenv("MISES_PRUSASLICER", raising=False)
    monkeypatch.setattr(slicer, "APP_PATH", tmp_path / "nope")
    monkeypatch.setattr(slicer, "USER_APP_PATH", tmp_path / "nope2")
    monkeypatch.setattr(slicer, "DRIVERS_APP_PATH", tmp_path / "nope3")
    monkeypatch.setattr(slicer, "_mdfind_bundles", lambda: [])
    monkeypatch.setattr("shutil.which", lambda *_: None)
    assert slicer.find_slicer() is None
    with pytest.raises(MisesError) as e:
        slicer.require_slicer()
    assert "brew install --cask prusaslicer" in (e.value.hint or "")
    st = slicer.slicer_status()
    assert st == {"installed": False, "path": None,
                  "install_command": "brew install --cask prusaslicer"}


def test_materials_and_models():
    assert {"PLA", "PETG", "ABS", "ASA", "TPU"} <= set(slicer.MATERIALS)
    assert set(slicer.PRINTER_MODELS) == {"MK4", "MINI"}
    ini = slicer.build_ini("MINI", "PETG")
    assert "bed_shape = 0x0,180x0,180x180,0x180" in ini
    assert "binary_gcode = 0" in ini and "thumbnails = 440x240/PNG" in ini
    assert "filament_density = 1.27" in ini and "temperature = 240" in ini
    with pytest.raises(MisesError, match="material"):
        slicer.build_ini("MK4", "unobtainium")
    with pytest.raises(MisesError, match="model"):
        slicer.build_ini("XYZ", "PLA")


def _fake_slicer(tmp_path, body: str) -> Path:
    p = tmp_path / "fake_prusaslicer"
    p.write_text(f"#!{sys.executable}\nimport sys\nargs=sys.argv[1:]\n{body}\n")
    p.chmod(p.stat().st_mode | stat.S_IXUSR)
    return p


async def test_run_slice_with_fake_slicer(tmp_path, monkeypatch):
    fake = _fake_slicer(tmp_path, f"""
out=args[args.index('--output')+1]
assert '--export-gcode' in args and '--load' in args
open(out,'w').write(open({str(FIXTURE)!r}).read())
""")
    monkeypatch.setenv("MISES_PRUSASLICER", str(fake))
    stl = tmp_path / "m.stl"
    stl.write_bytes(b"solid x\nendsolid x\n")
    res = await slicer.run_slice(stl, tmp_path / "out", model="MK4", material="PLA", timeout_s=20)
    assert res.gcode_path.read_text().startswith("; generated by PrusaSlicer")
    assert res.estimate.filament_g == pytest.approx(7.51)
    assert res.preview_png is not None and res.preview_png.read_bytes().startswith(b"\x89PNG")


async def test_run_slice_failure_and_timeout(tmp_path, monkeypatch):
    bad = _fake_slicer(tmp_path, "sys.stderr.write('Objects could not fit on the bed\\n'); sys.exit(1)")
    monkeypatch.setenv("MISES_PRUSASLICER", str(bad))
    stl = tmp_path / "m.stl"
    stl.write_bytes(b"x")
    with pytest.raises(MisesError, match="could not fit"):
        await slicer.run_slice(stl, tmp_path / "o1", model="MK4", material="PLA", timeout_s=20)
    hang = _fake_slicer(tmp_path, "import time; time.sleep(60)")
    monkeypatch.setenv("MISES_PRUSASLICER", str(hang))
    with pytest.raises(MisesError, match="timed out"):
        await slicer.run_slice(stl, tmp_path / "o2", model="MK4", material="PLA", timeout_s=1)


