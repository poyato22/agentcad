"""GET /parts/{id}/drawing.svg | .dxf | .json: the part's 2D engineering drawing (admin token).

Generated by the sandboxed CAD worker on first request and cached until the part, material or
date changes. The SVG is a picture: it is served with a CSP that forbids scripts and loads.
"""
from __future__ import annotations

from datetime import date
from pathlib import Path
from typing import TYPE_CHECKING

from fastapi import APIRouter, Response

from .. import mass as mass_mod
from ..cad import safe_io
from ..cad.tools import PART_ID_RE
from ..drawing import MATERIAL_RE, DrawingError, mirror_drawing
from ..types import ErrorCode, MisesError

if TYPE_CHECKING:
    from ..runtime import Runtime


def _read(path: Path) -> bytes:
    """A drawing file in the part dir, read without following a link (cad/safe_io)."""
    data = safe_io.read_bytes(path.parent, path.name)
    if data is None:
        raise MisesError(ErrorCode.NOT_FOUND, f"{path.name} is missing; request it again")
    return data


def build_drawing_router(runtime: Runtime) -> APIRouter:
    router = APIRouter()

    async def _drawing(part_id: str, material: str | None):
        if not PART_ID_RE.fullmatch(part_id):
            raise MisesError(ErrorCode.INVALID_INPUT, f"bad part id: {part_id!r}",
                             hint=f"part ids match {PART_ID_RE.pattern}")
        if material is not None and not MATERIAL_RE.match(material):
            raise MisesError(ErrorCode.INVALID_INPUT, "bad material name")
        d = Path(runtime.home) / "parts" / part_id
        if not (d / "model.step").is_file():
            raise MisesError(ErrorCode.NOT_FOUND, f"no built part {part_id!r}",
                             hint="build it with mirror_part_create")
        try:
            return await mirror_drawing(
                d, label=part_id, material=material or mass_mod.part_material(
                    runtime.store, runtime.home, part_id),
                date=date.today().isoformat())
        except DrawingError as e:
            raise MisesError(ErrorCode.TOOL_FAILED, str(e)) from None

    @router.get("/parts/{part_id}/drawing.svg")
    async def drawing_svg(part_id: str, material: str | None = None):
        d = await _drawing(part_id, material)
        return Response(_read(d.svg_path), media_type="image/svg+xml", headers={
            "Content-Security-Policy": "default-src 'none'; style-src 'unsafe-inline'",
            "Cache-Control": "private, no-cache"})

    @router.get("/parts/{part_id}/drawing.dxf")
    async def drawing_dxf(part_id: str, material: str | None = None):
        d = await _drawing(part_id, material)
        return Response(_read(d.dxf_path), media_type="image/vnd.dxf", headers={
            "Content-Disposition": f'attachment; filename="{part_id}.dxf"',
            "Cache-Control": "private, no-cache"})

    @router.get("/parts/{part_id}/drawing.json")
    async def drawing_json(part_id: str, material: str | None = None):
        return (await _drawing(part_id, material)).info

    return router
